r"""Generate PyCompat's tables from the Python that is the oracle, so they can't drift by hand.

    python tools/gen/gen_tables.py

Writes:
    src/PyCompat/PyHtmlEntities.g.cs                     html.entities.html5, the table html.unescape uses
    tests/PyCompat.Tests/Generated/PythonWhitespace.g.cs  every BMP code point str.isspace() and re's \s accept
                                                          (they must agree), for the test of PyStr.IsSpace
    src/PyCompat/PyUnicode.g.cs                          Python's own Unicode data where .NET's differs or is
                                                          missing: re's \w, \d and \s, str.isprintable, cased and
                                                          case-ignorable characters (found by probing str.lower),
                                                          the full lower and casefold mappings, and what re's
                                                          IGNORECASE uses (_sre's cased and lower, _EXTRA_CASES)
All carry the Python version they came from. Re-run after a Python upgrade and diff.
Merged from teams-channel-notes' tools/gen/gen_tables.py and onenote-sync's parity/gen_entities.py.
"""

from __future__ import annotations

import pathlib
import re
import sys
import unicodedata
from html.entities import html5

ROOT = pathlib.Path(__file__).resolve().parents[2]
VERSION = sys.version.split()[0]
BACKSLASH = chr(92)


def cs(text: str) -> str:
    """A C# string literal, with everything outside printable ASCII as four-digit \\uXXXX escapes (a two-digit
    \\x escape would swallow a following hex digit)."""
    out = []
    for ch in text:
        code = ord(ch)
        if code > 0xFFFF:
            code -= 0x10000
            out.append(f"{BACKSLASH}u{0xD800 + (code >> 10):04X}{BACKSLASH}u{0xDC00 + (code & 0x3FF):04X}")
        elif 0x20 <= code < 0x7F and ch not in ('"', BACKSLASH):
            out.append(ch)
        else:
            out.append(f"{BACKSLASH}u{code:04X}")
    return '"' + "".join(out) + '"'


def write(path: pathlib.Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def entities() -> None:
    lines = [
        "// <auto-generated>",
        f"// From Python {VERSION}'s html.entities.html5 by tools/gen/gen_tables.py. Don't edit by hand.",
        "// </auto-generated>",
        "namespace PyCompat;",
        "",
        "internal static class PyHtmlEntities",
        "{",
        f"    public const string PythonVersion = \"{VERSION}\";",
        "",
        "    /// <summary>Name, value, name, value... (names as html5 holds them: some with \";\", some without).</summary>",
        "    internal static readonly string[] Pairs =",
        "    [",
    ]
    for name in sorted(html5):
        lines.append(f"        {cs(name)}, {cs(html5[name])},")
    lines += ["    ];", "}", ""]
    path = ROOT / "src" / "PyCompat" / "PyHtmlEntities.g.cs"
    write(path, lines)
    print(f"{path.relative_to(ROOT)}: {len(html5)} entities")


def whitespace() -> None:
    spaces = [c for c in range(0x10000) if chr(c).isspace()]
    regex = [c for c in range(0x10000) if re.fullmatch(r"\s", chr(c))]
    assert spaces == regex, "str.isspace() and re's \\s disagree"
    lines = [
        "// <auto-generated>",
        f"// From Python {VERSION}'s str.isspace() by tools/gen/gen_tables.py. Don't edit by hand.",
        "// </auto-generated>",
        "namespace PyCompat.Tests;",
        "",
        "internal static class PythonWhitespace",
        "{",
        f"    public const string PythonVersion = \"{VERSION}\";",
        "",
        "    public static readonly int[] CodePoints =",
        "    [",
        "        " + ", ".join(f"0x{c:04X}" for c in spaces) + ",",
        "    ];",
        "}",
        "",
    ]
    path = ROOT / "tests" / "PyCompat.Tests" / "Generated" / "PythonWhitespace.g.cs"
    write(path, lines)
    print(f"{path.relative_to(ROOT)}: {len(spaces)} code points")


def ranges(code_points) -> list[tuple[int, int]]:
    out: list[list[int]] = []
    for c in code_points:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return [(lo, hi) for lo, hi in out]


def case_ignorable(c: int) -> bool:
    """Python's _PyUnicode_IsCaseIgnorable, which Python doesn't expose, read from str.lower()'s final-sigma rule:
    a capital sigma is final when a cased letter comes before it and none after, skipping case-ignorable ones."""
    ch = chr(c)
    cased = ch.islower() or ch.isupper() or ch.istitle()
    if cased:
        return ("AΣ" + ch).lower()[1] == "ς"   # skipped after the sigma, so nothing cased follows
    return ("A" + ch + "Σ").lower()[2] == "ς"   # skipped before the sigma, so "A" precedes it


def unicode_tables() -> None:
    import _sre
    from re._casefix import _EXTRA_CASES
    every = range(0x110000)
    word = [c for c in every if re.fullmatch(r"\w", chr(c))]
    digit = [c for c in every if re.fullmatch(r"\d", chr(c))]
    space = [c for c in every if re.fullmatch(r"\s", chr(c))]
    printable = [c for c in every if chr(c).isprintable()]
    cased = [c for c in every if chr(c).islower() or chr(c).isupper() or chr(c).istitle()]
    ignorable = [c for c in every if case_ignorable(c)]
    sre_cased = [c for c in every if _sre.unicode_iscased(c)]
    maps = {
        "Lower": ({c: chr(c).lower() for c in every if chr(c).lower() != chr(c)}, "str.lower() of each character it changes"),
        "CaseFold": ({c: chr(c).casefold() for c in every if chr(c).casefold() != chr(c)}, "str.casefold() of each character it changes"),
    }
    sre_lower = {c: _sre.unicode_tolower(c) for c in every if _sre.unicode_tolower(c) != c}
    # re's simple upper case is only needed beyond the BMP (RANGE_UNI_IGNORE), where every mapping is one character.
    sre_upper = {}
    for c in range(0x10000, 0x110000):
        u = chr(c).upper()
        if u != chr(c):
            assert len(u) == 1 and ord(u) >= 0x10000, hex(c)
            sre_upper[c] = ord(u)
    lines = [
        "// <auto-generated>",
        f"// From Python {VERSION} (Unicode {unicodedata.unidata_version}) by tools/gen/gen_tables.py. Don't edit by hand.",
        "// </auto-generated>",
        "namespace PyCompat;",
        "",
        "internal static partial class PyUnicode",
        "{",
        f"    public const string PythonVersion = \"{VERSION}\";",
        f"    public const string UnicodeVersion = \"{unicodedata.unidata_version}\";",
        "",
    ]
    for name, points, what in [
        ("Word", word, r"re's \w for str patterns"),
        ("Digit", digit, r"re's \d for str patterns"),
        ("Space", space, r"re's \s for str patterns (str.isspace)"),
        ("Printable", printable, "str.isprintable() of one character (what repr() leaves unescaped)"),
        ("Cased", cased, "cased characters: lower, upper or title case (Unicode's Cased property)"),
        ("CaseIgnorable", ignorable, "case-ignorable characters, for the final-sigma rule"),
        ("SreCased", sre_cased, "_sre.unicode_iscased: characters re's IGNORECASE treats as cased"),
    ]:
        pairs = ranges(points)
        lines += [f"    /// <summary>{what}: first, last, first, last... ({len(points)} code points).</summary>",
                  f"    internal static readonly int[] {name}Ranges =", "    ["]
        for i in range(0, len(pairs), 8):
            lines.append("        " + " ".join(f"0x{lo:X}, 0x{hi:X}," for lo, hi in pairs[i:i + 8]))
        lines += ["    ];", ""]
    for name, (mapping, what) in maps.items():
        keys = sorted(mapping)
        lines += [f"    /// <summary>{what}, in code point order.</summary>",
                  f"    internal static readonly int[] {name}From =", "    ["]
        for i in range(0, len(keys), 16):
            lines.append("        " + " ".join(f"0x{c:X}," for c in keys[i:i + 16]))
        lines += ["    ];", "", f"    internal static readonly string[] {name}To =", "    ["]
        for i in range(0, len(keys), 8):
            lines.append("        " + " ".join(cs(mapping[c]) + "," for c in keys[i:i + 8]))
        lines += ["    ];", ""]
    for name, mapping, what in [
        ("SreLower", sre_lower, "_sre.unicode_tolower (the simple lower case re's IGNORECASE compares)"),
        ("SreUpper", sre_upper, "the simple upper case beyond the BMP (re's RANGE_UNI_IGNORE)"),
    ]:
        keys = sorted(mapping)
        lines += [f"    /// <summary>{what}: from, to, from, to... in code point order ({len(keys)}).</summary>",
                  f"    internal static readonly int[] {name}Pairs =", "    ["]
        for i in range(0, len(keys), 8):
            lines.append("        " + " ".join(f"0x{c:X}, 0x{mapping[c]:X}," for c in keys[i:i + 8]))
        lines += ["    ];", ""]
    lines += ["    /// <summary>re._casefix._EXTRA_CASES: a lower-case character, then the others IGNORECASE treats as the",
              "    /// same (0 ends each list).</summary>",
              "    internal static readonly int[] ExtraCases =", "    ["]
    for k in sorted(_EXTRA_CASES):
        lines.append(f"        0x{k:X}, " + " ".join(f"0x{v:X}," for v in _EXTRA_CASES[k]) + " 0,")
    lines += ["    ];", "}", ""]
    path = ROOT / "src" / "PyCompat" / "PyUnicode.g.cs"
    write(path, lines)
    print(f"{path.relative_to(ROOT)}: {len(word)} word, {len(printable)} printable, " +
          ", ".join(f"{len(m)} {n.lower()}" for n, (m, _) in maps.items()) + f", {len(sre_lower)} sre lower")


if __name__ == "__main__":
    entities()
    whitespace()
    unicode_tables()
