def long_diff() -> tuple[list[str], list[str], int]:
    """250 lines with popular ones, so difflib's autojunk rule matters."""
    rng = random.Random(13)
    a = [("}" if i % 7 == 0 else f"line {rng.randint(0, 60)}") + "\n" for i in range(250)]
    b = list(a)
    for _ in range(25):
        i = rng.randrange(len(b))
        choice = rng.randrange(3)
        if choice == 0:
            b[i] = f"changed {rng.randint(0, 9)}\n"
        elif choice == 1:
            del b[i]
        else:
            b.insert(i, "}\n")
    return a, b, 3


