def lines() -> list[str]:
    out = [
        "// <auto-generated>",
        f"// From Python {VERSION} by tools/gen/gen_expected.py. Don't edit by hand.",
        "// </auto-generated>",
        "namespace PyCompat.Tests;",
        "",
        "internal static class PythonExpected",
        "{",
        f"    public const string PythonVersion = \"{VERSION}\";",
        "",
        "    /// <summary>datetime.fromisoformat(input).isoformat(), or \"ERR:\" and Python's message.</summary>",
        "    public static readonly (string Input, string Expected)[] DateTimes =",
        "    [",
    ]
    for text in DATETIMES:
        out.append(f"        ({cs(text)}, {cs(attempt(lambda: dt.datetime.fromisoformat(text).isoformat()))}),")
    out += ["    ];", "", "    /// <summary>time.fromisoformat(input).isoformat(), or \"ERR:\".</summary>",
            "    public static readonly (string Input, string Expected)[] Times =", "    ["]
    for text in TIMES:
        out.append(f"        ({cs(text)}, {cs(attempt(lambda: dt.time.fromisoformat(text).isoformat()))}),")
    out += ["    ];", "",
            "    /// <summary>A and B (lines with their endings), n, \"\".join(unified_diff(a, b, 'a', 'b', n=n)), and",
            "    /// \"\\n\".join(unified_diff(a without endings, b without endings, 'a', 'b', n=n, lineterm=\"\")).</summary>",
            "    public static readonly (string[] A, string[] B, int N, string Of, string Lines)[] Diffs =", "    ["]
    for a, b, n in [*DIFFS, long_diff()]:
        of = "".join(difflib.unified_diff(a, b, "a", "b", n=n))
        bare = "\n".join(difflib.unified_diff([x.rstrip("\n") for x in a], [x.rstrip("\n") for x in b], "a", "b", n=n, lineterm=""))
        out.append(f"        ([{', '.join(cs(x) for x in a)}], [{', '.join(cs(x) for x in b)}], {n}, {cs(of)}, {cs(bare)}),")
    out += ["    ];", "",
            "    /// <summary>A JSON text, then json.dumps(json.loads(text), ...) with indent None, ensure_ascii; indent 2,",
            "    /// ensure_ascii False; indent 1, sort_keys; indent 0, sort_keys, ensure_ascii False.</summary>",
            "    public static readonly (string Json, string Plain, string Indented, string Sorted, string ZeroSorted)[] Json =", "    ["]
    for text in JSON:
        value = json.loads(text)
        out.append("        (" + ", ".join(cs(x) for x in [
            text, json.dumps(value), json.dumps(value, indent=2, ensure_ascii=False), json.dumps(value, indent=1, sort_keys=True),
            json.dumps(value, indent=0, sort_keys=True, ensure_ascii=False)]) + "),")
    out += ["    ];", "", "    public static readonly (string Input, string Expected)[] Unescape =", "    ["]
    for text in UNESCAPE:
        out.append(f"        ({cs(text)}, {cs(html.unescape(text))}),")
    out += ["    ];", "", "    public static readonly (string Input, string Expected)[] Lower =", "    ["]
    for text in LOWER:
        out.append(f"        ({cs(text)}, {cs(text.lower())}),")
    out += ["    ];", "", "    /// <summary>str(int(input)), or \"ERR\" for a ValueError.</summary>",
            "    public static readonly (string Input, string Expected)[] Ints =", "    ["]
    for text in INTS:
        out.append(f"        ({cs(text)}, {cs(attempt(lambda: str(int(text))).split(':')[0] if attempt(lambda: str(int(text))).startswith('ERR') else str(int(text)))}),")
    out += ["    ];", "}", ""]
    return out


